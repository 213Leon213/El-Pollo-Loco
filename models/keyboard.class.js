/**
 * Represents the keyboard input state.
 */
class Keyboard {

    /** @type {boolean} Indicates whether the right key is pressed. */
    RIGHT = false;

    /** @type {boolean} Indicates whether the left key is pressed. */
    LEFT = false;

    /** @type {boolean} Indicates whether the space key is pressed. */
    SPACE = false;

    /** @type {boolean} Indicates whether the down key is pressed. */
    DOWN = false;

    /** @type {boolean} Indicates whether the up key is pressed. */
    UP = false;

    /** @type {boolean} Indicates whether the E key is pressed. */
    E = false;

    /** @type {boolean} Indicates whether the W key is pressed. */
    W = false;

    /** @type {boolean} Indicates whether the A key is pressed. */
    A = false;

    /** @type {boolean} Indicates whether the D key is pressed. */
    D = false;
}